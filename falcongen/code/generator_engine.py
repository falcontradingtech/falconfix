        fh.write("/*static */\n")
        fh.write("bool Session::buildPossDupReplay(std::string_view raw, std::string &out) {\n")
        fh.write(f"    constexpr char SOH = {ns}::serialize::SOH;\n\n")
        fh.write("    out.clear();\n")
        fh.write("    out.reserve(raw.size() + 96);\n\n")
        fh.write("    uint32_t checksum = 0;\n\n")
        fh.write("    auto appendChar = [&](char c) {\n")
        fh.write("        out.push_back(c);\n")
        fh.write("        checksum += static_cast<unsigned char>(c);\n")
        fh.write("    };\n\n")
        fh.write("    auto appendView = [&](std::string_view v) {\n")
        fh.write("        out.append(v.data(), v.size());\n\n")
        fh.write("        for (unsigned char c : v) {\n")
        fh.write("            checksum += c;\n")
        fh.write("        }\n")
        fh.write("    };\n\n")
        fh.write("    auto appendRaw = [&](const char *data, std::size_t size) {\n")
        fh.write("        out.append(data, size);\n\n")
        fh.write("        for (std::size_t i = 0; i < size; ++i) {\n")
        fh.write("            checksum += static_cast<unsigned char>(data[i]);\n")
        fh.write("        }\n")
        fh.write("    };\n\n")
        fh.write("    std::size_t bodyLengthValuePos = std::string::npos;\n")
        fh.write("    std::size_t bodyStartPos = std::string::npos;\n")
        fh.write("    std::size_t possDupInsertPos = std::string::npos;\n\n")
        fh.write("    std::string_view sendingTime{};\n\n")
        fh.write("    std::size_t pos = 0;\n\n")
        fh.write("    while (pos < raw.size()) {\n")
        fh.write("        const std::size_t fieldEnd = raw.find(SOH, pos);\n")
        fh.write("        if (fieldEnd == std::string_view::npos) [[unlikely]] {\n")
        fh.write("            return false;\n")
        fh.write("        }\n\n")
        fh.write("        const std::size_t eq = raw.find('=', pos);\n")
        fh.write("        if (eq == std::string_view::npos || eq > fieldEnd) [[unlikely]] {\n")
        fh.write("            return false;\n")
        fh.write("        }\n\n")
        fh.write("        int32_t tag = 0;\n\n")
        fh.write("        for (std::size_t i = pos; i < eq; ++i) {\n")
        fh.write("            const unsigned d = static_cast<unsigned>(raw[i] - '0');\n\n")
        fh.write("            if (d > 9) [[unlikely]] {\n")
        fh.write("                return false;\n")
        fh.write("            }\n\n")
        fh.write("            tag = (tag * 10) + static_cast<int32_t>(d);\n")
        fh.write("        }\n\n")
        fh.write("        switch (tag) {\n\n")
        fh.write(f"            case {ns}::field_id::CheckSum:\n")
        fh.write("                pos = raw.size();\n")
        fh.write("                continue;\n\n")
        fh.write(f"            case {ns}::field_id::BodyLength: {{\n")
        fh.write("                appendView(raw.substr(pos, eq - pos + 1));\n\n")
        fh.write("                bodyLengthValuePos = out.size();\n\n")
        fh.write("                appendView(\"000000\");\n")
        fh.write("                appendChar(SOH);\n\n")
        fh.write("                bodyStartPos = out.size();\n\n")
        fh.write("                pos = fieldEnd + 1;\n")
        fh.write("                continue;\n")
        fh.write("            }\n\n")
        fh.write(f"            case {ns}::field_id::SendingTime:\n")
        fh.write("                sendingTime = raw.substr(eq + 1, fieldEnd - eq - 1);\n")
        fh.write("                break;\n\n")
        fh.write("            default:\n")
        fh.write("                break;\n")
        fh.write("        }\n\n")
        fh.write("        appendRaw(raw.data() + pos, fieldEnd - pos + 1);\n\n")
        fh.write("        switch (tag) {\n\n")
        fh.write(f"            case {ns}::field_id::MsgType: {{\n")
        fh.write("                possDupInsertPos = out.size();\n\n")
        fh.write("                char tmp[16];\n")
        fh.write("                char *p = tmp;\n\n")
        fh.write(f"                WRITE_TAG3({ns}::tag_const::PossDupFlag); // 43=\n")
        fh.write("                *p++ = 'Y';\n")
        fh.write("                *p++ = SOH;\n\n")
        fh.write("                appendRaw(tmp, static_cast<std::size_t>(p - tmp));\n")
        fh.write("                break;\n")
        fh.write("            }\n\n")
        fh.write("            default:\n")
        fh.write("                break;\n")
        fh.write("        }\n\n")
        fh.write("        pos = fieldEnd + 1;\n")
        fh.write("    }\n\n")
