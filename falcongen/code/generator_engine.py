def _write_session_cpp(out_path: Path, ns: str, include_root: str):
    with open_generated_file(out_path, encoding="utf-8") as fh:
        write_autogen_header(fh, f"{include_root} generated session implementation")
        fh.write(f"#include <{include_root}/engine/session.h>\n\n")
        fh.write("#include <utility>\n")
        fh.write("#include <vector>\n\n")
        fh.write(f"#include <{include_root}/engine/inbound_dispatch.h>\n")
