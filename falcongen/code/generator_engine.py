def _build_context(spec: dict):
    ns = namespace_from_spec(spec)
    version = spec.get("fix_version") or spec.get("version")
    if not version:
        raise ValueError("spec is missing FIX version (expected 'fix_version' or 'version')")
    include_root = normalize_version_string(version)
    msgtype_members = {}
    session_reject_members = set()
    for field in spec.get("fields", []):
        if field.get("name") == "MsgType":
            for idx, value in enumerate(field.get("values", [])):
                enum_value = value.get("enum")
                if not enum_value:
                    continue
                msgtype_members[enum_value] = safe_enum_name(value.get("description"), idx)
        elif field.get("name") == "SessionRejectReason":
            for idx, value in enumerate(field.get("values", [])):
                session_reject_members.add(safe_enum_name(value.get("description"), idx))
    return ns, include_root, msgtype_members, session_reject_members


def _pick_session_reject_member(session_reject_members: set[str], *candidates: str) -> str:
    for candidate in candidates:
        if candidate in session_reject_members:
            return candidate
    if session_reject_members:
        return sorted(session_reject_members)[0]
    raise ValueError("SessionRejectReason enum is missing from spec")


def _protocol_version_number(include_root: str) -> int:
    if not include_root.startswith("FIX"):
        raise ValueError(f"unsupported FIX version format: {include_root}")
    parts = include_root[3:].split(".")
    if len(parts) != 2 or not all(part.isdigit() for part in parts):
        raise ValueError(f"unsupported FIX version format: {include_root}")
    return int(parts[0]) * 10 + int(parts[1])


def _protocol_version_enum(include_root: str) -> str:
    mapping = {
        "FIX4.0": "FIX40",
        "FIX4.1": "FIX41",
        "FIX4.2": "FIX42",
        "FIX4.3": "FIX43",
        "FIX4.4": "FIX44",
        "FIX5.0": "FIX50",
        "FIX5.0SP1": "FIX50SP1",
        "FIX5.0SP2": "FIX50SP2",
        "FIXT1.1": "FIXT11",
    }
    try:
        return mapping[include_root]
    except KeyError as exc:
        raise ValueError(f"unsupported FIX version format: {include_root}") from exc


def _write_protocol_header(out_path: Path, ns: str, include_root: str):
    protocol_version = _protocol_version_enum(include_root)

    with open_generated_file(out_path, encoding="utf-8") as fh:
        write_autogen_header(fh, f"{include_root} generated protocol constants")
        fh.write("#pragma once\n\n")
        fh.write("#include <string_view>\n\n")
        fh.write("#include <app/fix_message_ref.h>\n\n")
        fh.write(f"namespace {ns}::engine {{\n")
        fh.write("class Session;\n")
        fh.write("}\n\n")
        fh.write(f"namespace {ns} {{\n\n")
        fh.write("struct Protocol {\n")
        fh.write(f"\tstatic constexpr falconfix::ProtocolVersion VERSION = falconfix::ProtocolVersion::{protocol_version};\n")
        fh.write(f"\tstatic constexpr std::string_view BEGIN_STRING = \"{include_root}\";\n\n")
        fh.write(f"\tusing SessionType = {ns}::engine::Session;\n")
        fh.write("};\n\n")
        fh.write(f"}} // namespace {ns}\n")


