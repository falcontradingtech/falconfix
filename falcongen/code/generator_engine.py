        fh.write(f"#include <{include_root}/utils/tag_constants.h>\n\n")
        fh.write(f"namespace {ns}::engine {{\n\n")
        fh.write("Session::Session(falconfix::FIXApplication &app,\n")
        fh.write("                 const falconfix::SessionConfig &cfg,\n")
        fh.write("                 std::unique_ptr<falconfix::MessageLog> log,\n")
        fh.write("                 std::unique_ptr<falconfix::MessageStore> store)\n")
        fh.write("    : m_sid(cfg.sessionID),\n")
        fh.write("      m_app(app),\n")
        fh.write("      m_cfg(cfg),\n")
        fh.write("      m_log(std::move(log)),\n")
        fh.write("      m_store(std::move(store)) {\n")
        fh.write("\tm_sidText = m_sid.toString();\n\n")
        fh.write("\tif (!m_log) {\n")
        fh.write("\t\tm_log = std::make_unique<falconfix::NullMessageLog>();\n")
        fh.write("\t}\n")
        fh.write("\tif (!m_store) {\n")
        fh.write("\t\tm_store = std::make_unique<falconfix::NullMessageStore>();\n")
        fh.write("\t}\n")
        fh.write("}\n\n")
        fh.write("FFStatus Session::doLogout(std::string_view reason) noexcept {\n")
        fh.write("    std::lock_guard<std::recursive_mutex> lock(m_mutex);\n\n")
        fh.write("    if (m_state.closing() ||\n")
        fh.write("        m_state.status == falconfix::SessionStatus::Disconnected) {\n")
        fh.write("        return FF_OK();\n")
        fh.write("    }\n\n")
        fh.write("    if (m_state.awaitingResend) {\n")
        fh.write("        m_state.status = falconfix::SessionStatus::Closing;\n")
        fh.write("        return FF_OK();\n")
        fh.write("    }\n\n")
        fh.write("    return sendLogout(reason);\n")
        fh.write("}\n\n")
        fh.write("FFStatus Session::onReceive(const char *data, std::size_t size) noexcept {\n")
        fh.write("    std::lock_guard<std::recursive_mutex> lock(m_mutex);\n\n")
        fh.write("    if (m_state.status == falconfix::SessionStatus::Disconnected) {\n")
        fh.write("        return FF_OK();\n")
        fh.write("    }\n\n")
        fh.write("    if (!data && size > 0) [[unlikely]] {\n")
        fh.write("        return FF_FIX_PARSE_ERR(INVALID_LENGTH, 0);\n")
        fh.write("    }\n\n")
        fh.write("    const bool hasPending = !m_in.empty();\n")
        fh.write("    if (hasPending || size == 0) {\n")
        fh.write("        if (size > 0) {\n")
        fh.write("            if (!m_in.reserve_noexcept(m_in.size() + size)) [[unlikely]] {\n")
        fh.write("                return FF_SYS_ERR(OUT_OF_MEMORY);\n")
        fh.write("            }\n")
        fh.write("            m_in.append(data, size);\n")
        fh.write("        }\n")
        fh.write("        data = m_in.data();\n")
        fh.write("        size = m_in.size();\n")
        fh.write("    }\n\n")
        fh.write("    const bool usingPending = !m_in.empty();\n")
        fh.write("    const char *cursor = data;\n")
        fh.write("    const char *end = data + size;\n")
        fh.write("    const char *bufferBegin = cursor;\n\n")
        fh.write("    while (cursor < end) {\n")
        fh.write("        TCPFrameView frame;\n\n")
        fh.write("        FFStatus rc = parseTCPFrame(cursor, static_cast<std::size_t>(end - cursor), frame);\n")
        fh.write("        if (isIncompleteTCPFrame(rc)) [[unlikely]] {\n")
        fh.write("            if (usingPending) {\n")
        fh.write("                const std::size_t processed = static_cast<std::size_t>(cursor - bufferBegin);\n")
        fh.write("                if (processed > 0) {\n")
        fh.write("                    m_in.consume(processed);\n")
        fh.write("                }\n")
        fh.write("            }\n")
        fh.write("            else {\n")
        fh.write("                const std::size_t remaining = static_cast<std::size_t>(end - cursor);\n")
        fh.write("                if (!m_in.reserve_noexcept(remaining)) [[unlikely]] {\n")
        fh.write("                    return FF_SYS_ERR(OUT_OF_MEMORY);\n")
        fh.write("                }\n")
        fh.write("                m_in.append(cursor, remaining);\n")
        fh.write("            }\n")
        fh.write("\n")
        fh.write("            return FF_OK();\n")
        fh.write("        }\n")
        fh.write("        if (!rc.ok()) [[unlikely]] {\n")
        fh.write("            if (usingPending) {\n")
        fh.write("                m_in.clear();\n")
        fh.write("            }\n")
