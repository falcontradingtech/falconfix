_CONTENT_HASH_PLACEHOLDER = "__FALCONFIX_CONTENT_HASH__"
_CONTENT_HASH_LINE = f"ContentHash: {_CONTENT_HASH_PLACEHOLDER}"
_GENERATED_BY_LINE = "Generated by FalconFIX Generator"


def _finalize_generated_content(content: str) -> str:
    if _CONTENT_HASH_PLACEHOLDER not in content:
        return content

    content_without_hash = content.replace(_CONTENT_HASH_LINE, "ContentHash:", 1)
    digest = hashlib.sha256(content_without_hash.encode("utf-8")).hexdigest()[:16]
    return content.replace(_CONTENT_HASH_PLACEHOLDER, digest, 1)


class _GeneratedFileBuffer(io.StringIO):
    def __init__(self, path: Path, encoding: str = "utf-8"):
        super().__init__()
        self._path = Path(path)
        self._encoding = encoding

    def close(self) -> None:
        if not self.closed:
            final_content = _finalize_generated_content(self.getvalue())
            previous_content = None
            if self._path.exists():
                previous_content = self._path.read_text(encoding=self._encoding)

            if previous_content != final_content:
                self._path.parent.mkdir(parents=True, exist_ok=True)
                self._path.write_text(final_content, encoding=self._encoding)

        super().close()


class _GeneratedFileContext:
    def __init__(self, path: Path, encoding: str = "utf-8"):
        self._buffer = _GeneratedFileBuffer(path, encoding=encoding)

    def __enter__(self) -> TextIO:
        return self._buffer

    def __exit__(self, exc_type, exc, tb) -> bool:
        self._buffer.close()
        return False


def open_generated_file(path: Path, encoding: str = "utf-8") -> _GeneratedFileContext:
    return _GeneratedFileContext(path, encoding=encoding)


# ===== AUTOGENERATION HEADER =====

def write_autogen_header(
    f: TextIO,
    description: str = "Auto-generated FIX code",
) -> None:
    """
    Writes boilerplate header for auto-generated file.

    Args:
        f: File handle aberto para escrita
        description: Description of what the file is
    """
    _ = description
    write_generated_line_header(f)


def write_generated_line_header(
    f: TextIO,
    comment_prefix: str = "//",
    *description_lines: str,
) -> None:
    f.write(f"{comment_prefix} {_GENERATED_BY_LINE}\n")
    f.write(f"{comment_prefix} {_CONTENT_HASH_LINE}\n")
    for line in description_lines:
        f.write(f"{comment_prefix} {line}\n")
    f.write("\n")


# ===== NAMESPACE MANAGEMENT =====

def write_namespace_open(f: TextIO, namespace: str, indent_spaces: int = 0) -> None:
    """
    Escreve abertura de namespace.

    Args:
        f: File handle
        namespace: Nome do namespace (ex: "fix44")
        indent_spaces: Initial indentation

    Exemplo output:
        namespace fix44 {
    """
    prefix = " " * indent_spaces
    f.write(f"{prefix}namespace {namespace} {{\n\n")


def write_namespace_close(f: TextIO, namespace: str, indent_spaces: int = 0) -> None:
    """
    Escreve fechamento de namespace.

    Args:
        f: File handle
        namespace: Nome do namespace
        indent_spaces: Indentation

    Exemplo output:
        } // namespace fix44
    """
    prefix = " " * indent_spaces
    f.write(f"\n{prefix}}} // namespace {namespace}\n")


